import { useEffect, useRef, useState } from "react";
import { useParams } from "react-router-dom";
import {
  Bar, BarChart, Cell, ResponsiveContainer, XAxis, YAxis,
} from "recharts";
import { getSignal } from "../api.js";
import {
  Disclaimer, DirectionBadge, ModelBadge, RiskBadge, SentimentBadge,
  SourceBadge, fmtUsd, scoreColor,
} from "../components/ui.jsx";

export default function Stock() {
  const { ticker } = useParams();
  const [data, setData] = useState(null);
  const [error, setError] = useState("");

  useEffect(() => {
    setData(null);
    setError("");
    getSignal(ticker.toUpperCase())
      .then(setData)
      .catch((e) => setError(
        e.response?.status === 404
          ? `${ticker.toUpperCase()} is not in the current signal set.`
          : `Could not load ${ticker}: ${e.message}`));
  }, [ticker]);

  if (error) return <main className="page"><div className="error-box">{error}</div></main>;
  if (!data) return <main className="page"><p className="muted">Loading…</p></main>;

  const { signal, prediction, trades, news, explanation } = data;
  const T = ticker.toUpperCase();

  return (
    <main className="page">
      <div className="row spread">
        <h1 style={{ margin: 0 }}>
          {T} <span className="muted" style={{ fontWeight: 400 }}>
            {signal?.company}</span>
        </h1>
        <div className="row">
          {signal && <RiskBadge risk={signal.risk} />}
          {prediction && <DirectionBadge direction={prediction.direction} />}
        </div>
      </div>

      <div className="card mt"><TradingViewChart ticker={T} /></div>

      <div className="mt" style={{ display: "grid", gap: 14,
                                   gridTemplateColumns: "repeat(auto-fit, minmax(300px, 1fr))" }}>
        <div className="card">
          <div className="muted small">Convergence score</div>
          <div className="score-big" style={{ color: scoreColor(signal?.score ?? 0) }}>
            {signal?.score ?? "—"}
          </div>
          <div className="muted small mt">
            {signal?.buyers ?? 0} distinct buyers
            ({signal?.congress_buyers ?? 0} congress,{" "}
            {signal?.billionaire_buyers ?? 0} billionaire,{" "}
            {signal?.insider_buyers ?? 0} insider) ·
            disclosed buying ≈ {fmtUsd(signal?.total_buy_usd)}
          </div>
        </div>
        <PredictionPanel prediction={prediction} />
      </div>

      <h2>Insider trades for {T}</h2>
      <div className="card" style={{ overflowX: "auto" }}>
        {trades.length === 0 ? (
          <p className="muted">No tracked trades for this ticker.</p>
        ) : (
          <table>
            <thead>
              <tr>
                <th>Source</th><th>Trader</th><th>Detail</th><th>Type</th>
                <th>Amount</th><th>Trade date</th><th>Disclosed</th>
              </tr>
            </thead>
            <tbody>
              {trades.map((t) => (
                <tr key={t.id}>
                  <td><SourceBadge source={t.source} /></td>
                  <td>{t.trader}</td>
                  <td className="muted small">{t.detail}</td>
                  <td>
                    <span className={`badge ${t.type === "buy" ? "bullish" : "bearish"}`}>
                      {t.type.toUpperCase()}
                    </span>
                  </td>
                  <td>{t.source === "billionaire"
                    ? fmtUsd(t.amount_usd) : t.amount_range}</td>
                  <td className="mono small">{t.trade_date}</td>
                  <td className="mono small muted">{t.disclosure_date}</td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </div>

      <h2>AI explanation</h2>
      <div className="card explanation">
        {explanation
          ? <Markdown text={explanation.text} />
          : <p className="muted">No explanation generated yet —
              run <code>python main.py explain</code>.</p>}
        {explanation && (
          <p className="muted small mt">
            Generated by {explanation.model} · {explanation.updated_at}
          </p>
        )}
      </div>

      <h2>News</h2>
      <div className="card">
        {news.length === 0 ? (
          <p className="muted">No recent headlines.</p>
        ) : news.slice(0, 5).map((n) => (
          <div className="news-row" key={n.id}>
            <a href={n.url} target="_blank" rel="noopener noreferrer">
              {n.headline}
            </a>
            <div className="row small muted" style={{ marginTop: 2 }}>
              <span>{n.source}</span>·<span>{n.published}</span>
              <SentimentBadge value={n.sentiment} />
            </div>
          </div>
        ))}
      </div>

      <Disclaimer />
    </main>
  );
}

function TradingViewChart({ ticker }) {
  const ref = useRef(null);
  useEffect(() => {
    if (!ref.current) return;
    ref.current.innerHTML = "";
    const script = document.createElement("script");
    script.src = "https://s3.tradingview.com/external-embedding/embed-widget-symbol-overview.js";
    script.async = true;
    script.innerHTML = JSON.stringify({
      symbols: [[ticker]],
      chartOnly: false,
      width: "100%",
      height: 400,
      colorTheme: "dark",
      backgroundColor: "rgba(22, 27, 34, 1)",
      autosize: true,
      showVolume: true,
      dateRanges: ["1m|30", "3m|60", "12m|1D", "60m|1W"],
    });
    ref.current.appendChild(script);
  }, [ticker]);
  return <div ref={ref} style={{ minHeight: 400 }} />;
}

function PredictionPanel({ prediction }) {
  if (!prediction) {
    return (
      <div className="card">
        <div className="muted small">Prediction</div>
        <p className="muted">No model prediction for this ticker yet.</p>
      </div>
    );
  }
  const p = prediction;
  const conf = Math.round((p.confidence || 0) * 100);
  const targets = [
    { name: "1d", pct: p.pct_1d, target: p.target_1d },
    { name: "3d", pct: p.pct_3d, target: p.target_3d },
    { name: "7d", pct: p.pct_7d, target: p.target_7d },
  ];
  return (
    <div className="card">
      <div className="row spread">
        <div className="muted small">Kronos prediction</div>
        <ModelBadge model={p.model} />
      </div>
      <div className="row mt">
        <DirectionBadge direction={p.direction} />
        <span className="muted small">
          last price ${p.last_price?.toFixed(2)}
        </span>
      </div>
      <div className="muted small mt">Confidence — {conf}%</div>
      <div style={{ height: 46 }}>
        <ResponsiveContainer width="100%" height="100%">
          <BarChart layout="vertical" data={[{ name: "conf", value: conf }]}
                    margin={{ top: 8, bottom: 8 }}>
            <XAxis type="number" domain={[0, 100]} hide />
            <YAxis type="category" dataKey="name" hide />
            <Bar dataKey="value" radius={[4, 4, 4, 4]} background={{ fill: "rgba(139,148,158,0.2)" }}>
              <Cell fill={conf >= 65 ? "var(--bullish)"
                : conf >= 45 ? "var(--neutral)" : "var(--bearish)"} />
            </Bar>
          </BarChart>
        </ResponsiveContainer>
      </div>
      {conf <= 40 && (
        <div className="muted small mt" style={{ color: "var(--neutral)" }}>
          ⚠ Low confidence — the model's raw forecast exceeded this stock's
          typical volatility and was capped. Treat the targets below as a
          bound, not an estimate.
        </div>
      )}
      <table className="mt">
        <thead>
          <tr><th>Horizon</th><th>Move</th><th>Price target</th></tr>
        </thead>
        <tbody>
          {targets.map((t) => (
            <tr key={t.name}>
              <td className="mono">{t.name}</td>
              <td style={{ color: t.pct >= 0 ? "var(--bullish)" : "var(--bearish)" }}>
                {t.pct >= 0 ? "+" : ""}{t.pct?.toFixed(1)}%
              </td>
              <td className="mono">${t.target?.toFixed(2)}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

function Markdown({ text }) {
  // Minimal renderer for the explanation markdown (## headings + bold).
  const bold = (s) =>
    s.split(/\*\*(.+?)\*\*/g).map((part, i) =>
      i % 2 === 1 ? <strong key={i}>{part}</strong> : part);
  return (
    <>
      {text.split("\n").map((line, i) => {
        const t = line.trim();
        if (!t) return null;
        if (t.startsWith("##")) return <h3 key={i}>{t.replace(/^#+\s*/, "")}</h3>;
        return <p key={i}>{bold(t)}</p>;
      })}
    </>
  );
}
