def system_prompt(name: str) -> str:
    """The full reusable prompt for one persona: role + task spec + the
    shared trust-tier rules, injection guard, and disclaimer requirement."""
    if name not in PERSONAS:
        raise ValueError(f"unknown persona: {name}")
    role, spec = PERSONAS[name]
    return (
        f"{role}\n\n"
        f"TASK: {spec}\n\n"
        f"{TRUST_RULES}\n\n"
        f"{INJECTION_GUARD}\n\n"
        f"Every deliverable must end with this disclaimer, verbatim:\n"
        f"\"{DISCLAIMER}\"")
