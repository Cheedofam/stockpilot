"""Multi-persona equity-research engine.

Five "analyst desk" personas, each a structured prompt that turns StockPilot's
own data (convergence signal, prediction, recent news) plus the user's investor
profile into a professional research section via Gemini, with a deterministic
template fallback so output is always produced (mirrors explainer.py):

  goldman_screener   — equity screen: valuation, growth, leverage, moat,
                       bull/bear targets, risk score, entry/stop levels
  ms_dcf             — discounted-cash-flow valuation with sensitivity + verdict
  bridgewater_risk   — portfolio risk: correlation, concentration, rate/recession
                       stress, position sizing, hedges, rebalancing
  jpm_earnings       — earnings history vs expectations, segment + guidance review
  blackrock_portfolio— asset allocation, ETF core/satellite, DCA, tax-efficiency

These are EDUCATIONAL research scaffolds, not investment advice. The personas
are framed as "in the style of"; every report carries a not-advice disclaimer
and is grounded only in the facts passed to it.
"""

from __future__ import annotations

import json

from . import config, db

GEMINI_MODELS = ["gemini-2.5-flash", "gemini-2.5-flash-lite",
                 "gemini-2.0-flash", "gemini-2.0-flash-lite"]

_DISCLAIMER = (
    "This is educational research generated by StockPilot, not investment "
    "advice. Figures may be estimates or stale; verify against your broker "
    "before acting. Disclosures and fundamentals lag reality. You decide.")

# Each persona: (role line, the exact deliverable spec the section must cover).
PERSONAS: dict[str, tuple[str, str]] = {
    "goldman_screener": (
        "You are a senior equity analyst at Goldman Sachs with 20 years of "
        "experience screening stocks for high-net-worth clients.",
        "Produce a professional equity research note covering: P/E ratio vs "
        "sector average; 5-year revenue growth trend; debt-to-equity; dividend "
        "sustainability score; competitive moat rating; bull and bear price "
        "targets; a risk score (1-10); and concrete entry zones and stop-loss "
        "levels."),
    "ms_dcf": (
        "You are a VP-level investment banker at Morgan Stanley.",
        "Build a complete DCF valuation: 5-year revenue projections; operating "
        "margin forecasts; free-cash-flow estimates; WACC calculation (state "
        "the risk-free rate, equity risk premium and beta you assume); a "
        "sensitivity table on WACC and terminal growth; an intrinsic value "
        "estimate; comparison to the current price; and an "
        "Overvalued/Fair/Undervalued verdict. Show your assumptions explicitly "
        "and label every number as an estimate."),
    "bridgewater_risk": (
        "You are a risk analyst at Bridgewater Associates.",
        "Analyze: portfolio correlation risk; sector concentration; geographic "
        "exposure; interest-rate sensitivity; a recession stress test; "
        "liquidity; position-sizing recommendations sized to the investor's "
        "capital; hedging opportunities; and rebalancing suggestions. Assume "
        "the investor is starting from 100% cash unless told otherwise."),
    "jpm_earnings": (
        "You are an equity research analyst at JPMorgan.",
        "Provide: earnings history vs expectations; revenue and EPS forecasts; "
        "key metrics to monitor; segment growth analysis (break down where "
        "revenue actually comes from in plain terms); management guidance "
        "review; options-market expectations; historical earnings reactions; "
        "and bull and bear scenarios."),
    "blackrock_portfolio": (
        "You are a portfolio strategist at BlackRock.",
        "Create: asset-allocation percentages; specific ETF recommendations "
        "(low-fee, suitable for a Canadian investor); core vs satellite "
        "positions; expected returns and drawdown estimates; a tax-efficient "
        "account strategy (explain TFSA vs RRSP vs FHSA vs taxable for a "
        "Canadian, including US-dividend withholding); a rebalancing plan; and "
        "a dollar-cost-averaging schedule sized to the investor's capital."),
}

DEFAULT_PERSONAS = list(PERSONAS)


def _profile() -> dict:
    """The investor profile block from config (drives every persona)."""
    p = config.load().get("investor_profile", {})
    return p if isinstance(p, dict) else {}


def _ticker_context(ticker: str) -> dict:
    """StockPilot's own facts for a ticker, to ground the persona."""
    con = db.connect()
    sig = con.execute("SELECT * FROM signals WHERE ticker=?",
                      (ticker,)).fetchone()
    pred = con.execute("SELECT * FROM predictions WHERE ticker=?",
                       (ticker,)).fetchone()
    news = con.execute("SELECT headline, sentiment FROM news WHERE ticker=? "
                       "ORDER BY published DESC LIMIT 5", (ticker,)).fetchall()
    con.close()
    ctx: dict = {"ticker": ticker}
    if sig:
        ctx["stockpilot_signal"] = {
            k: sig[k] for k in ("score", "buyers", "congress_buyers",
                                "billionaire_buyers", "insider_buyers", "risk")}
        ctx["stockpilot_signal"]["buyer_names"] = json.loads(
            sig["buyer_names"] or "[]")
    if pred:
        ctx["stockpilot_prediction"] = {
            k: pred[k] for k in ("direction", "confidence", "model",
                                 "last_price", "pct_7d")}
    if news:
        ctx["recent_headlines"] = [n["headline"] for n in news]
    return ctx


def _gemini(prompt: str) -> str | None:
    key = config.get("gemini_api_key", "")
    if not key:
        return None
    try:
        import google.generativeai as genai
        genai.configure(api_key=key)
    except Exception:
        return None
    for name in GEMINI_MODELS:
        try:
            resp = genai.GenerativeModel(name).generate_content(prompt)
            text = (resp.text or "").strip()
            if text:
                return text
        except Exception:
            continue
    return None


def _build_prompt(persona: str, ticker: str | None, ctx: dict) -> str:
    role, spec = PERSONAS[persona]
    return (
        f"{role}\n\n"
        f"TASK: {spec}\n\n"
        "Write in clean markdown, lead with a one-line bottom line, be concrete "
        "and educational, avoid hype, and never promise returns. Use ONLY the "
        "facts in the JSON below; where a figure is unknown, say so or label it "
        "an estimate rather than inventing precision. End with a one-line "
        "disclaimer that this is not investment advice.\n\n"
        f"INVESTOR PROFILE:\n{json.dumps(_profile(), indent=1)}\n\n"
        f"FACTS{(' for ' + ticker) if ticker else ''}:\n"
        f"{json.dumps(ctx, indent=1)}")


def _template(persona: str, ticker: str | None) -> str:
    role, spec = PERSONAS[persona]
    head = f"## {persona.replace('_', ' ').title()}"
    if ticker:
        head += f" — {ticker}"
    return (f"{head}\n\n_{role}_\n\nNo Gemini API key configured, so this is a "
            f"placeholder. With a key, this section would deliver: {spec}\n\n"
            f"> {_DISCLAIMER}")


def analyze(persona: str, ticker: str | None = None) -> tuple[str, str]:
    """Run one persona (optionally for a ticker). Returns (markdown, model)."""
    if persona not in PERSONAS:
        raise ValueError(f"unknown persona: {persona}")
    ctx = _ticker_context(ticker) if ticker else {}
    text = _gemini(_build_prompt(persona, ticker, ctx))
    if text:
        return text, "gemini"
    return _template(persona, ticker), "template"


def run_analyst(ticker: str | None = None,
                personas: list[str] | None = None) -> dict:
    """Run the requested personas, persist each report, return a status dict."""
    personas = personas or _profile().get("personas") or DEFAULT_PERSONAS
    personas = [p for p in personas if p in PERSONAS]
    con = db.connect()
    used: dict[str, int] = {}
    for p in personas:
        text, model = analyze(p, ticker)
        db.replace_analyst_report(con, ticker or "_PORTFOLIO", p, text, model)
        used[model] = used.get(model, 0) + 1
        print(f"  {p} ({model})")
    con.commit()
    con.close()
    return {"ticker": ticker or "_PORTFOLIO", "personas": personas,
            "models": used}
